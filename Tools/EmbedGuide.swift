import Foundation

// Build-time only: keep GUIDE.md as the source of truth without reading it
// from a potentially protected folder when the user opens the guide.
guard CommandLine.arguments.count == 3 else {
    fatalError("Usage: EmbedGuide.swift GUIDE.md output.swift")
}
let markdown = try String(contentsOfFile: CommandLine.arguments[1], encoding: .utf8)
let source = "// Generated by Tools/EmbedGuide.swift. Do not edit.\nenum EmbeddedGuide {\n    static let markdown = \(String(reflecting: markdown))\n}\n"
try source.write(toFile: CommandLine.arguments[2], atomically: true, encoding: .utf8)
